"""IP ranges that only Microsoft 365's own servers use.

Some audit records show the IP of a Microsoft 365 server instead of the
client: Outlook mobile syncs through a Microsoft service, and Teams, Copilot,
and other Microsoft apps read mail with the user's token from Microsoft's
servers. Such an IP does not show where the user or an attacker is, so the
session and mail access checks skip these records (sign-ins excepted).

Two sources:

- microsoft_nets.json (generated by scripts/update_microsoft_nets.py): each
  range of the Office 365 endpoints list, minus every range of every Azure
  service tag. Azure service tags include all Azure address space that a
  customer can use (VMs, Front Door, and other services that can relay a
  request). What is left is Microsoft 365 server space only.
- INTERNAL_NETS (below, kept by hand): Exchange Online server space that is
  in neither list. Add a prefix only after it shows up in a real record, and
  only if it is in no Azure service tag.

CI checks both every month (.github/workflows/microsoft-nets.yml). If the
JSON file is missing or cannot be read, only INTERNAL_NETS applies: the
checks then alert on more records, not fewer.
"""

import bisect
import ipaddress
import json
import logging
from functools import lru_cache
from pathlib import Path

DATA_FILE = Path(__file__).with_name("microsoft_nets.json")

# 2603:10b6::/32: Exchange Online servers in North America (it is in the Received headers of NAM
# mail). Seen as the ClientIPAddress of Outlook-iOS MailItemsAccessed records, November 2026.
INTERNAL_NETS = (
    "2603:10b6::/32",
)


def load_prefixes(path: Path = DATA_FILE) -> list:
    """The prefixes in the generated file, or [] if it cannot be read."""
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return [str(ipaddress.ip_network(p)) for p in data["prefixes"]]
    except Exception as e:
        logging.warning(f"Microsoft 365 IP ranges not loaded: {type(e).__name__}")
        return []


@lru_cache(maxsize=1)
def _ranges() -> dict:
    """{IP version: (sorted range starts, range ends)} of the merged ranges."""
    nets = [ipaddress.ip_network(p) for p in (*load_prefixes(), *INTERNAL_NETS)]
    out = {}
    for version in (4, 6):
        merged = ipaddress.collapse_addresses(n for n in nets if n.version == version)
        pairs = sorted((int(n.network_address), int(n.broadcast_address)) for n in merged)
        out[version] = ([s for s, _ in pairs], [e for _, e in pairs])
    return out


def is_service_ip(ip) -> bool:
    """True if ``ip`` is in a range that only Microsoft 365's servers use."""
    try:
        addr = ipaddress.ip_address(str(ip or "").strip())
    except ValueError:
        return False
    starts, ends = _ranges()[addr.version]
    i = bisect.bisect_right(starts, int(addr)) - 1
    return i >= 0 and int(addr) <= ends[i]
